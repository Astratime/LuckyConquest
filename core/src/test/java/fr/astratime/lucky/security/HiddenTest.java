package fr.astratime.lucky.security;

import fr.astratime.lucky.progress.PlayerProfile;

import org.junit.jupiter.api.Test;

import java.lang.reflect.Field;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Les chaînes sensibles rangées sous forme codée redonnent bien leur valeur
 * d'origine (garde-fou contre une faute de frappe dans les tableaux).
 */
class HiddenTest {

    @Test
    void revealGivesBackTheExpectedStrings() {
        assertEquals("lucky-conquest-profile", Hidden.reveal(new int[]{0x57, 0x35, 0x26, 0x21, 0x36,
            0x79, 0x3a, 0x31, 0x0d, 0x19, 0x18, 0x17, 0x04, 0x08, 0xac, 0xf6, 0xf9, 0xff, 0xf3, 0xf3, 0xf3, 0xc1}));
        assertEquals(".prefs", Hidden.reveal(new int[]{0x15, 0x30, 0x37, 0x2f, 0x29, 0x27}));
        assertEquals("lucky-conquest-crash.log", Hidden.reveal(new int[]{0x57, 0x35, 0x26, 0x21, 0x36,
            0x79, 0x3a, 0x31, 0x0d, 0x19, 0x18, 0x17, 0x04, 0x08, 0xac, 0xe5, 0xf9, 0xf1, 0xe6, 0xf2, 0xb1, 0xc8, 0xc6, 0xc9}));
        assertEquals("LUCKY-CONQUEST-SAVE", Hidden.reveal(new int[]{0x77, 0x15, 0x06, 0x01, 0x16,
            0x79, 0x1a, 0x11, 0x2d, 0x39, 0x38, 0x37, 0x24, 0x28, 0xac, 0xd5, 0xca, 0xc6, 0xd0}));
        assertEquals("lucky-conquest-save", Hidden.reveal(new int[]{0x57, 0x35, 0x26, 0x21, 0x36,
            0x79, 0x3a, 0x31, 0x0d, 0x19, 0x18, 0x17, 0x04, 0x08, 0xac, 0xf5, 0xea, 0xe6, 0xf0}));
        assertEquals("lucky-conquest-last-slot", Hidden.reveal(new int[]{0x57, 0x35, 0x26, 0x21, 0x36,
            0x79, 0x3a, 0x31, 0x0d, 0x19, 0x18, 0x17, 0x04, 0x08, 0xac, 0xea, 0xea, 0xe3, 0xe1, 0xb7, 0xec, 0xc8, 0xc6, 0xda}));
    }

    @Test
    void adminKeysKeepTheirExactValues() throws Exception {
        // Les sauvegardes existantes utilisent ces noms de clés : ils ne doivent pas changer.
        assertEquals("adminDeck", staticString(PlayerProfile.class, "KEY_ADMIN_DECK"));
        assertEquals("adminMachine", staticString(PlayerProfile.class, "KEY_ADMIN_MACHINE"));
    }

    private static String staticString(Class<?> type, String name) throws Exception {
        Field field = type.getDeclaredField(name);
        field.setAccessible(true);
        return (String) field.get(null);
    }
}
